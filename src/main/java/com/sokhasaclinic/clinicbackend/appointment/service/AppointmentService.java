    private AppointmentSnapshot change(UUID id, Long expectedVersion, AppointmentStatus next, Actor actor,
            String reason, BiConsumer<Appointment, Instant> transition) {
        Appointment appointment = lockForChange(id, expectedVersion, next);
        AppointmentStatus from = appointment.getStatus();
        Instant now = clock.instant();
        transition.accept(appointment, now);
        appointments.saveAndFlush(appointment);
        record(appointment, from, actor, reason, now);
        return AppointmentSnapshot.of(appointment);
    }

    /**
     * Loads the appointment with a row lock and checks, in contract order, that it exists
     * ({@code 404}), that the caller sent the current version ({@code 428}, {@code 412}) and that the
     * step is allowed ({@code 409 INVALID_TRANSITION}). {@code expectedVersion} is null when
     * {@code If-Match} was missing.
     */
    private Appointment lockForChange(UUID id, Long expectedVersion, AppointmentStatus next) {
        Appointment appointment = appointments.findForUpdate(id)
                .orElseThrow(AppointmentException::appointmentNotFound);
        if (expectedVersion == null) {
            throw AppointmentException.versionRequired();
        }
        if (appointment.getVersion() != expectedVersion) {
            throw AppointmentException.versionMismatch();
        }
        if (!appointment.getStatus().canMoveTo(next)) {
            throw AppointmentException.invalidTransition(appointment.getStatus(), next);
        }
        return appointment;
    }

