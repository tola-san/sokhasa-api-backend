    /**
     * Creates a {@code PENDING} request if the period still has room (capacity rule). The date and
     * period are locked while counting, so two requests for the last minutes cannot both succeed;
     * the loser gets {@code 409 PERIOD_FULL} and nothing is created.
     */
    @Transactional
    public AppointmentSnapshot request(BookingCommand command) {
        return request(command, UUID.randomUUID()).appointment();
    }

    /**
     * As {@link #request(BookingCommand)}, once per Idempotency-Key (AP-03). Requests with the same
     * key are serialised; a repeat with the same request returns the first appointment
     * ({@code replayed}), and a repeat with a different request fails with
     * {@code 409 IDEMPOTENCY_CONFLICT}. Failed requests are not stored, so a retry is checked again.
     */
    @Transactional
    public BookingResult request(BookingCommand command, UUID idempotencyKey) {
        PatientDetails details = validateDetails(command);
        LocalDate date = command.preferredDate();
        if (date == null) {
            throw AppointmentException.invalidField("preferredDate", "Choose a date.");
        }
        boolean exact = command.preferredStartTime() != null;
        if (exact == (command.preferredPeriod() != null)) {
            throw AppointmentException.invalidField("preferredStartTime",
                    "Send exactly one of preferredPeriod or preferredStartTime.");
        }
        if (command.serviceId() == null) throw AppointmentException.serviceNotFound();
        // Replay before mutable service/schedule/window checks: a successful booking must still
        // replay after midnight or a service-duration edit while its key is retained.
        String selector = exact ? "TIME:" + command.preferredStartTime() : command.preferredPeriod();
        String preferredSlug = command.preferredDoctorSlug() == null || command.preferredDoctorSlug().isBlank()
                ? null : command.preferredDoctorSlug().strip();
        // PD-09: the preference is part of the request. Requests without one keep their old hash.
        if (preferredSlug != null) selector += "\u001fDOCTOR:" + preferredSlug;
        String requestHash = RequestHash.of(command.serviceId(), date, selector, details);
        idempotencyKeys.lock(idempotencyKey);
        Optional<IdempotencyKeys.StoredKey> stored = idempotencyKeys.find(idempotencyKey);
        if (stored.isPresent()) {
            if (!stored.get().requestHash().equals(requestHash)) {
                throw AppointmentException.idempotencyConflict();
            }
            Appointment first = appointments.findById(stored.get().appointmentId())
                    .orElseThrow(AppointmentException::appointmentNotFound);
            return new BookingResult(AppointmentSnapshot.of(first), true);
        }

        LocalDate today = LocalDate.now(clock.withZone(ClinicTime.ZONE));
        if (date.isBefore(today)) {
            throw AppointmentException.invalidField("preferredDate", "Choose today or a later date.");
        }
        int windowDays = settings.windowDays();
        if (date.isAfter(today.plusDays(windowDays))) {
            throw AppointmentException.invalidField("preferredDate",
                    "Choose a date within the next " + windowDays + " days.");
        }
        ClinicService service = findBookableService(command.serviceId());
        UUID preferredDoctorId = preferredSlug == null ? null : preferredDoctor(preferredSlug, service.getId());
        BookingPeriod period = exact
                ? slots.period(command.preferredStartTime(), service.getDurationMinutes() + service.getBufferMinutes())
                : findPeriod(command.preferredPeriod());

        periodLock.lock(date, period.getCode());
        long used = appointments.minutesUsed(date, period.getCode());
        int needed = service.getDurationMinutes() + service.getBufferMinutes();
        if (used + needed > period.getCapacityMinutes()) {
            throw AppointmentException.periodFull();
        }

        Instant now = clock.instant();
        Patient patient = findOrCreatePatient(details.fullName(), details.phone(), now);
        Appointment appointment = Appointment.request(patient, service, references.next(date), details, date, period, now);
        if (preferredDoctorId != null) appointment.preferDoctor(preferredDoctorId);
        if (exact) {
            var window = slots.reserve(service.getId(), date, command.preferredStartTime(), needed, period.getCode(), now,
                    preferredDoctorId);
            appointment.reserve(window.id(), window.doctorId(), command.preferredStartTime(),
                    date.atTime(command.preferredStartTime()).atZone(ClinicTime.ZONE).toInstant());
        }
        try {
            appointments.saveAndFlush(appointment);
        } catch (DataIntegrityViolationException e) {
            if (exact && isDoctorOverlap(e)) throw AppointmentException.slotUnavailable();
            throw e;
        }
        record(appointment, null, Actor.guest(), null, now);
        idempotencyKeys.save(idempotencyKey, requestHash, appointment.getId(), now);
        notifications.appointmentCreated(AppointmentSnapshot.of(appointment));
        return new BookingResult(AppointmentSnapshot.of(appointment), false);
    }

    /** AP-04 and AP-05: trims, normalises and checks the patient's fields. */
    private static PatientDetails validateDetails(BookingCommand command) {
        String fullName = requireName(command.fullName());
        String phone = PhoneNumbers.normalize(command.phone())
                .orElseThrow(() -> AppointmentException.invalidField("phone", "Enter a valid phone number."));
        String language = command.languageCode();
        if (language == null || !LANGUAGES.contains(language)) {
            throw AppointmentException.invalidField("language", "Choose km, en or zh.");
        }
        String email = command.email() == null || command.email().isBlank() ? null : command.email().strip();
        if (email != null && (email.length() > MAX_EMAIL_LENGTH || !EMAIL.matcher(email).matches())) {
            throw AppointmentException.invalidField("email", "Enter a valid email address.");
        }
        String notes = command.notes() == null || command.notes().isBlank() ? null : command.notes().strip();
        if (notes != null && notes.length() > MAX_NOTES_LENGTH) {
            throw AppointmentException.invalidField("notes", "Notes can be up to " + MAX_NOTES_LENGTH + " characters.");
        }
        return new PatientDetails(fullName, phone, email, language, notes);
    }

